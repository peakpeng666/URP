OWNERSHIP_PAIRS = {'uid_check':'UID_CHECK_FAILED','gid_check':'GID_CHECK_FAILED','ownership_change':'OWNERSHIP_COMMAND_FAILED'}

def validate(value):
    if type(value) is not dict or set(value) != {'schema','stage','substage','code','exception_class'}:
        return None
    if type(value['schema']) is not int or value['schema'] != 1:
        return None
    if any(type(value[k]) is not str for k in ('stage','substage','code','exception_class')):
        return None
    stage = value['stage']
    if stage not in STAGES:
        return None
    row = STAGES[stage]
    if value['code'] not in row['codes'] or value['substage'] not in row['substages']:
        return None
    if stage == 'input_ownership':
        if value['exception_class'] != 'ShellExit' or OWNERSHIP_PAIRS[value['substage']] != value['code']:
            return None
    elif value['exception_class'] == 'SystemCAFailure' and stage != 'closure_verify':
        return None
    elif value['exception_class'] not in CLASSES:
        return None
    return dict(value)
